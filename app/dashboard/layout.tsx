export default function DashboardLayout({ children }: { children: ReactNode }) {
  const pathname = usePathname();
  const router = useRouter();

  async function logout() {
    const supabase = createClient();
    await supabase.auth.signOut();
    router.push('/login');
  }

  return (
    <div className="min-h-screen flex bg-bg-base">
      <aside className="w-16 flex flex-col items-center py-6 gap-1 shrink-0 border-r border-border bg-bg-surface">
        <div className="w-8 h-8 rounded-lg flex items-center justify-center mb-6 text-xs font-bold bg-accent-blue/15 text-accent-blue">
          S
        </div>

        {nav.map(item => {
          const active = pathname === item.href;
          return (
            <Link
              key={item.href}
              href={item.href}
              title={item.label}
              className="relative w-10 h-10 rounded-xl flex items-center justify-center transition-colors"
              style={{
                color: active ? 'var(--color-accent-blue)' : 'var(--color-text-muted)',
                background: active ? 'rgba(59,130,246,0.10)' : 'transparent',
              }}
            >
              {active && (
                <span className="absolute left-0 w-[3px] h-5 bg-accent-blue rounded-r" />
              )}
              {item.icon}
            </Link>
          );
        })}

        <button
          onClick={logout}
          title="Sair"
          className="mt-auto w-10 h-10 rounded-xl flex items-center justify-center transition-colors text-text-muted hover:text-text-primary"
        >
          <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round">
            <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
            <polyline points="16 17 21 12 16 7" />
            <line x1="21" y1="12" x2="9" y2="12" />
          </svg>
        </button>
      </aside>

      <main className="flex-1 p-8 overflow-auto">{children}</main>
    </div>
  );
}
